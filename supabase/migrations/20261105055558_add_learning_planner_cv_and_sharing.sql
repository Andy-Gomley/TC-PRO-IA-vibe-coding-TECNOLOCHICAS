/*
# Add planning, CV, and sharing data

1. New Tables
- `study_plans`: one private weekly study-planning configuration per signed-in learner, including selected days, start time, duration, and topics.
- `cv_profiles`: one private CV draft per signed-in learner, storing structured resume sections and the preferred translation language.
- `progress_shares`: private sharing preferences and public share token for a learner's progress profile.
2. Security
- Enable row-level security on all new tables.
- Grant CRUD only to authenticated users.
- Every policy checks ownership with `auth.uid()`.
3. Notes
- JSONB fields keep the planner topics and CV sections flexible without deleting existing learner data.
- The public token is generated by the app when the learner chooses to share progress.
*/

CREATE TABLE IF NOT EXISTS public.study_plans (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL UNIQUE DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  selected_days text[] NOT NULL DEFAULT ARRAY['Lun', 'Mié', 'Vie'],
  start_time time NOT NULL DEFAULT '18:00',
  duration_minutes integer NOT NULL DEFAULT 45 CHECK (duration_minutes > 0 AND duration_minutes <= 240),
  topics text[] NOT NULL DEFAULT ARRAY['Fundamentos de SQL'],
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.cv_profiles (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL UNIQUE DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  sections jsonb NOT NULL DEFAULT '{}'::jsonb,
  translation_language text NOT NULL DEFAULT 'English',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.progress_shares (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL UNIQUE DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  is_enabled boolean NOT NULL DEFAULT false,
  share_token text NOT NULL UNIQUE DEFAULT encode(gen_random_bytes(12), 'hex'),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.study_plans ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.cv_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.progress_shares ENABLE ROW LEVEL SECURITY;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.study_plans TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.cv_profiles TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.progress_shares TO authenticated;

DROP POLICY IF EXISTS "Users can read own study plan" ON public.study_plans;
CREATE POLICY "Users can read own study plan" ON public.study_plans FOR SELECT TO authenticated USING (auth.uid() = user_id);
DROP POLICY IF EXISTS "Users can create own study plan" ON public.study_plans;
CREATE POLICY "Users can create own study plan" ON public.study_plans FOR INSERT TO authenticated WITH CHECK (auth.uid() = user_id);
DROP POLICY IF EXISTS "Users can update own study plan" ON public.study_plans;
CREATE POLICY "Users can update own study plan" ON public.study_plans FOR UPDATE TO authenticated USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
DROP POLICY IF EXISTS "Users can delete own study plan" ON public.study_plans;
CREATE POLICY "Users can delete own study plan" ON public.study_plans FOR DELETE TO authenticated USING (auth.uid() = user_id);

